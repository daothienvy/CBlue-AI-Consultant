def get_archetype_for_program(category_str, program_name=""):
    cat = category_str.strip() if category_str else ""
    p_name = program_name.lower()
    
    # Priority checks on program name
    if "golden visa" in p_name or "mprp" in p_name or "investor" in p_name or "gip" in p_name:
        return "golden_visa"
    if "digital nomad" in p_name or "white card" in p_name or "remote work" in p_name or "d8" in p_name:
        return "digital_nomad"
    if "blue card" in p_name or "chancenkarte" in p_name or "work permit" in p_name or "skilled worker" in p_name or "critical skills" in p_name:
        return "blue_card"
    if "fip" in p_name or "thu nhập thụ động" in p_name or "visiteur" in p_name or "non-lucrative" in p_name or "d7" in p_name or "elective" in p_name or "wealthy" in p_name or "private means" in p_name:
        return "passive_income"
    if "startup" in p_name or "entrepreneur" in p_name or "đổi mới" in p_name or "business" in p_name:
        return "startup_entrepreneur"
        
    for k, v in CATEGORY_MAP.items():
        if k.lower() in cat.lower():
            return v
            
    return "blue_card" # Default fallback
